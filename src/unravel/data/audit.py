"""Data audit: measure the dataset's real properties before any modelling decision relies on them."""

from __future__ import annotations

from datetime import UTC, datetime

import numpy as np
import polars as pl

from unravel.config import DatasetPaths
from unravel.eval.splits import MINUTES_PER_DAY, make_split
from unravel.features.fx import fit_fx


def _when(minute: int) -> str:
    return datetime.fromtimestamp(minute * 60, tz=UTC).strftime("%Y-%m-%d %H:%M")


def _table(frame: pl.DataFrame) -> str:
    header = "| " + " | ".join(frame.columns) + " |"
    rule = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(str(v) for v in row) + " |" for row in frame.iter_rows()]
    return "\n".join([header, rule, *rows])


def run_audit(paths: DatasetPaths) -> str:
    """Return the audit as Markdown. Every figure here is computed from the processed files."""
    tx = pl.read_parquet(paths.transactions)
    labels = pl.read_parquet(paths.labels)
    joined = tx.join(labels, on="tx_id", how="inner", maintain_order="left")
    minutes = joined["minute"].to_numpy()
    y = joined["is_laundering"].to_numpy()
    split = make_split(minutes)
    partition = split.assign(minutes)
    positives = int(y.sum())

    out: list[str] = [f"# Data audit: {paths.name}", "", "Generated by `unravel audit`.", ""]
    out += ["## Overview", ""]
    out += [
        f"- Transactions: **{joined.height:,}**",
        f"- Laundering transactions: **{positives:,}** "
        f"(1 in {joined.height / max(positives, 1):,.0f}; {100 * positives / joined.height:.4f}%)",
        f"- Time range: {_when(int(minutes.min()))} to {_when(int(minutes.max()))}",
        f"- Sending accounts: {joined['src'].n_unique():,}; "
        f"receiving accounts: {joined['dst'].n_unique():,}; "
        f"all accounts: {pl.concat([joined['src'], joined['dst']]).n_unique():,}",
        f"- Banks: {pl.concat([joined['from_bank'], joined['to_bank']]).n_unique():,}",
        "",
    ]

    daily = (
        joined.with_columns(
            ((pl.col("minute") - int(minutes.min())) // MINUTES_PER_DAY).alias("day")
        )
        .group_by("day")
        .agg(
            pl.len().alias("transactions"),
            pl.col("is_laundering").cast(pl.Int64).sum().alias("laundering"),
        )
        .sort("day")
        .with_columns(
            (pl.col("laundering") / pl.col("transactions") * 100).round(4).alias("rate_pct")
        )
    )
    out += ["## Daily volume", "", _table(daily), ""]

    names = ["train", "val_a", "val_b", "test"]
    rows = []
    for code, name in enumerate(names):
        mask = partition == code
        rows.append(
            {
                "partition": name,
                "start": _when(int(minutes[mask].min())),
                "end": _when(int(minutes[mask].max())),
                "transactions": int(mask.sum()),
                "share_pct": round(100 * float(mask.mean()), 2),
                "laundering": int(y[mask].sum()),
                "rate_pct": round(100 * float(y[mask].mean()), 4),
            }
        )
    out += [
        "## Split",
        "",
        f"Day boundaries from IBM's search: {split.train_days} train, {split.val_days} validation, "
        f"{split.test_days} test.",
        "",
        _table(pl.DataFrame(rows)),
        "",
    ]

    named = joined.filter(pl.col("pattern").is_not_null())
    out += [
        "## Named patterns",
        "",
        f"- {named.height:,} of {positives:,} laundering transactions "
        f"({100 * named.height / max(positives, 1):.1f}%) belong to a named pattern.",
        f"- Named instances matched: {named['pattern_instance'].n_unique():,}.",
        "",
    ]
    if named.height:
        with_partition = named.with_columns(
            pl.Series("partition", np.array(names)[split.assign(named["minute"].to_numpy())])
        )
        by_pattern = (
            with_partition.group_by("pattern")
            .agg(
                pl.col("pattern_instance").n_unique().alias("instances"),
                pl.len().alias("transactions"),
                (pl.col("partition") == "test").sum().alias("test_transactions"),
                pl.col("pattern_instance")
                .filter(pl.col("partition") == "test")
                .n_unique()
                .alias("test_instances"),
            )
            .sort("pattern")
        )
        straddle = (
            with_partition.group_by("pattern_instance")
            .agg(pl.col("partition").n_unique().alias("parts"))
            .filter(pl.col("parts") > 1)
            .height
        )
        span = (
            named.group_by("pattern", "pattern_instance")
            .agg(((pl.col("minute").max() - pl.col("minute").min()) / 60).alias("hours"))
            .group_by("pattern")
            .agg(
                pl.col("hours").median().round(1).alias("median_hours"),
                pl.col("hours").max().round(1).alias("max_hours"),
            )
            .sort("pattern")
        )
        out += [
            _table(by_pattern),
            "",
            f"Instances straddling a split boundary: {straddle}.",
            "",
            "Time span per instance:",
            "",
            _table(span),
            "",
        ]

    keys = [c for c in tx.columns if c not in ("tx_id", "order_key")]
    duplicates = joined.height - joined.select(keys).n_unique()
    out += [
        "## Data quality",
        "",
        f"- Exact duplicate rows (ignoring derived IDs): {duplicates:,}",
        f"- Self-transfers: {int((joined['src'] == joined['dst']).sum()):,}",
        f"- Cross-currency rows: "
        f"{int((joined['payment_currency'] != joined['receiving_currency']).sum()):,}",
        f"- Zero amounts: {int((joined['amount_paid'] <= 0).sum()):,}",
        f"- Busiest minute: {joined.group_by('minute').len()['len'].to_numpy().max():,} transactions "
        f"(mean {joined.height / joined['minute'].n_unique():.1f} per active minute)",
        "",
    ]

    train = joined.filter(pl.col("minute") < split.val_start)
    rates = fit_fx(train)
    every = sorted(
        set(joined["payment_currency"].unique()) | set(joined["receiving_currency"].unique())
    )
    missing = [c for c in every if c not in rates]
    out += [
        "## FX rates implied by training rows",
        "",
        "| currency | USD per unit |",
        "|---|---|",
        *[f"| {c} | {rates[c]:.6g} |" for c in rates],
        "",
        f"Currencies with no implied rate: {missing or 'none'}.",
        "",
    ]

    categories = ["payment_format", "payment_currency"]
    out += ["## Single-feature signal: possible generator artefacts", ""]
    for column in categories:
        table = (
            joined.group_by(column)
            .agg(
                pl.len().alias("n"),
                pl.col("is_laundering").cast(pl.Int64).sum().alias("laundering"),
            )
            .with_columns((pl.col("laundering") / pl.col("n") * 100).round(4).alias("rate_pct"))
            .sort("rate_pct", descending=True)
        )
        out += [f"**{column}**", "", _table(table), ""]
    return "\n".join(out)
