"""Build ``docs/results.md`` from the JSON reports, so that no number in the docs is hand-typed."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from unravel.config import ROOT, DatasetPaths
from unravel.eval.ledger import read_ledger
from unravel.experiments import LEDGER_NAME

PUBLISHED = [
    ("GIN", "28.70 ± 1.13", "Altman et al., Table 2"),
    ("PNA", "56.77 ± 2.41", "Altman et al., Table 2"),
    ("GFP + LightGBM", "62.86 ± 0.25", "Altman et al., Table 2"),
    ("GFP + XGBoost", "63.23 ± 0.17", "Altman et al., Table 2"),
    ("Multi-PNA + EU", "68.16 ± 2.65", "Egressy et al., Table 2"),
]
ARM_NAMES = {
    "T1": "T1: transaction fields only",
    "T2": "T2: + rolling account features",
    "T3": "T3: + graph features",
    "T3x": "T3x: T3 with XGBoost",
    "T3-nofmt": "T3-nofmt: T3 without payment format",
}


def _load(path: Path) -> Any:
    return json.loads(path.read_text()) if path.exists() else None


def _pm(mean: float, std: float, scale: float = 100.0, digits: int = 2) -> str:
    return f"{mean * scale:.{digits}f} ± {std * scale:.{digits}f}"


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    return [
        "| " + " | ".join(headers) + " |",
        "|" + "---|" * len(headers),
        *["| " + " | ".join(row) + " |" for row in rows],
        "",
    ]


def _avg(runs: list[dict[str, Any]], *keys: str) -> float:
    values = []
    for run in runs:
        node: Any = run
        for key in keys:
            node = node[key]
        values.append(float(node))
    return sum(values) / len(values)


def _std(runs: list[dict[str, Any]], *keys: str) -> float:
    values = []
    for run in runs:
        node: Any = run
        for key in keys:
            node = node[key]
        values.append(float(node))
    mean = sum(values) / len(values)
    if len(values) < 2:
        return 0.0
    return (sum((v - mean) ** 2 for v in values) / (len(values) - 1)) ** 0.5


def build_results(name: str = "HI-Small") -> str:
    paths = DatasetPaths(name)
    reports = paths.reports
    validation = reports / "validation"
    test = reports / "test"
    out: list[str] = [
        "# Results",
        "",
        f"Generated by `unravel report` from `reports/{name}/`. Dataset: IBM AMLworld {name}.",
        "",
    ]

    # -- test ----------------------------------------------------------------------------------
    test_arms = {arm: _load(test / f"{arm}.json") for arm in ARM_NAMES}
    test_arms = {k: v for k, v in test_arms.items() if v}
    ledger = read_ledger(reports / LEDGER_NAME)
    if test_arms:
        out += ["## Detection on the test set", ""]
        out += [
            f"Test-set evaluations on record: **{len(ledger)}**, counting each seed of each arm, "
            "two early T3 runs repeated with fewer bootstrap samples, and one G2 run repeated "
            "after its report failed to write. "
            "Model and threshold choices were made on validation.",
            "",
        ]
        rows = []
        for arm, result in test_arms.items():
            runs = result["runs"]
            rows.append(
                [
                    ARM_NAMES[arm],
                    str(len(runs)),
                    _pm(_avg(runs, "minority_f1", "f1"), _std(runs, "minority_f1", "f1")),
                    _pm(
                        _avg(runs, "full_volume_days", "minority_f1", "f1"),
                        _std(runs, "full_volume_days", "minority_f1", "f1"),
                    ),
                    f"{_avg(runs, 'pr_auc'):.4f}",
                    f"{_avg(runs, 'full_volume_days', 'pr_auc'):.4f}",
                ]
            )
        out += _table(
            [
                "Arm",
                "Seeds",
                "F1 %, all test days",
                "F1 %, full-volume days",
                "PR-AUC, all",
                "PR-AUC, full-volume",
            ],
            rows,
        )
        out += [
            "**Comparing with published work.** The all-days column uses the same day boundaries "
            "as the published results, but our features are our own and the published GNNs use "
            "non-causal neighbour sampling. Published figures on HI-Small:",
            "",
        ]
        out += _table(["Model", "Minority F1 %", "Source"], [list(row) for row in PUBLISHED])
        out += [
            "The full-volume column removes the laundering-only tail described in "
            "`docs/protocol.md`, and is the more honest estimate of real detection quality.",
            "",
        ]

        champion = test_arms.get("T3")
        if champion:
            runs = champion["runs"]
            first = runs[0]["full_volume_days"]
            out += ["## Precision at analyst capacity", ""]
            out += [
                f"T3 on the {int(first['capacity']['100']['days'])} full-volume test days, across "
                f"{len(runs)} seeds. This is few days, so treat these as indicative. The ceiling "
                "is the best any model could reach at that capacity.",
                "",
            ]
            rows = []
            for k in ("50", "100", "200", "500"):
                rows.append(
                    [
                        k,
                        f"{100 * _avg([r['full_volume_days'] for r in runs], 'capacity', k, 'precision'):.1f}%",
                        f"{100 * _avg([r['full_volume_days'] for r in runs], 'capacity', k, 'recall'):.1f}%",
                        f"{100 * first['capacity'][k]['recall_ceiling']:.1f}%",
                        f"{100 * _avg([r['full_volume_days'] for r in runs], 'capacity', k, 'case_precision'):.1f}%",
                        f"{100 * _avg([r['full_volume_days'] for r in runs], 'capacity', k, 'pattern_hit_rate'):.1f}%",
                        f"{100 * _avg([r['full_volume_days'] for r in runs], 'capacity', k, 'value_captured'):.1f}%",
                    ]
                )
            out += _table(
                [
                    "Alerts/day",
                    "Precision",
                    "Recall",
                    "Recall ceiling",
                    "Case precision",
                    "Pattern hit rate",
                    "Value captured",
                ],
                rows,
            )
            day_rows = []
            for row in first["capacity"]["100"]["per_day"]:
                day_rows.append(
                    [
                        str(int(row["day"])),
                        f"{int(row['transactions']):,}",
                        str(int(row["positives"])),
                        f"{100 * row['precision']:.1f}%",
                        f"{100 * row['recall']:.1f}%",
                    ]
                )
            out += ["Per day at 100 alerts (seed 0):", ""]
            out += _table(["Day", "Transactions", "Laundering", "Precision", "Recall"], day_rows)
            rate = [r["full_volume_days"]["rate"] for r in runs]
            regret = runs[0]["online_regret_full_volume"]
            out += [
                f"Precision at a fixed 0.02% of volume: "
                f"{100 * sum(x['precision'] for x in rate) / len(rate):.1f}%.",
                "",
                f"Live policy against the offline oracle at 100/day (seed 0, "
                f"{int(regret['days_evaluated'])} days evaluated): live precision "
                f"{100 * regret['live_precision']:.1f}%, oracle {100 * regret['oracle_precision']:.1f}%, "
                f"{regret['live_alerts_per_day']:.0f} alerts a day, "
                f"{int(regret['true_positives_lost'])} true positives fewer than the oracle.",
                "",
            ]

            patterns = runs[0]["full_volume_days"].get("per_pattern", {})
            if patterns:
                out += ["## Recall by pattern", ""]
                arms = {
                    k: v["runs"][0]["full_volume_days"]["per_pattern"] for k, v in test_arms.items()
                }
                rows = []
                for pattern in sorted(patterns):
                    rows.append(
                        [
                            pattern,
                            str(int(patterns[pattern]["n"])),
                            *[
                                f"{100 * arms[a].get(pattern, {}).get('recall', 0):.0f}%"
                                for a in arms
                            ],
                        ]
                    )
                out += ["Full-volume test days, seed 0, at each arm's validation F1 threshold.", ""]
                out += _table(["Pattern", "n", *list(arms)], rows)

            calibration_runs = [r for r in runs if "calibration_calibrated" in r]
            if calibration_runs:
                raw = calibration_runs[0]["calibration_raw"]
                cal = calibration_runs[0]["calibration_calibrated"]
                out += ["## Calibration on the test set", ""]
                out += [
                    f"T3 seed 0, method chosen on validation: `{calibration_runs[0]['calibration_method']}`. "
                    "This window includes the tail, where prevalence differs sharply from "
                    "validation, so it is also a prior-shift stress test.",
                    "",
                ]
                out += _table(
                    [
                        "",
                        "Log loss",
                        "Brier",
                        "Brier skill",
                        "Adaptive ECE",
                        "Mean predicted",
                        "Observed",
                    ],
                    [
                        [
                            label,
                            f"{c['log_loss']:.5f}",
                            f"{c['brier']:.6f}",
                            f"{c['brier_skill']:.4f}",
                            f"{c['adaptive_ece']:.5f}",
                            f"{c['mean_predicted']:.5f}",
                            f"{c['observed_rate']:.5f}",
                        ]
                        for label, c in (("Raw", raw), ("Calibrated", cal))
                    ],
                )

    gnn_rows = []
    gnn_patterns: dict[str, dict[str, Any]] = {}
    for path in sorted(test.glob("G*_seed*.json")):
        result = _load(path)
        label = f"{result['arm']}, {result['protocol']}"
        full = result["full_volume_days"]
        gnn_rows.append(
            [
                label,
                f"{100 * result['minority_f1']['f1']:.2f}",
                f"{100 * full['minority_f1']['f1']:.2f}",
                f"{result['pr_auc']:.4f}",
                f"{full['pr_auc']:.4f}",
                f"{100 * full['capacity']['100']['precision']:.1f}%",
            ]
        )
        gnn_patterns[label] = full["per_pattern"]
    if gnn_rows:
        out += ["## Graph neural networks on the test set", ""]
        out += [
            "**These are CPU-budget runs**: one seed, 8 epochs, hidden size 48, neighbours (15, 5) "
            "and 20 negatives per positive. Training curves were still improving when they stopped. "
            "They don't reproduce published GNN results, which took hours per run on a GPU with far "
            "larger neighbourhoods, and they don't show the limit of the method.",
            "",
            "- **G1:** plain PNA. **G2:** Multi-PNA + EU, neighbours may come from later edges (P1).",
            "- **G3:** Multi-PNA + EU, strictly earlier edges (P2). **G4:** G3 plus T2 features.",
            "",
        ]
        out += _table(
            [
                "Arm",
                "F1 %, all test days",
                "F1 %, full-volume days",
                "PR-AUC, all",
                "PR-AUC, full-volume",
                "Precision@100",
            ],
            gnn_rows,
        )
        champion_run = test_arms.get("T3")
        if champion_run:
            trees = champion_run["runs"][0]["full_volume_days"]["per_pattern"]
            rows = []
            for pattern in sorted(trees):
                rows.append(
                    [
                        pattern,
                        str(int(trees[pattern]["n"])),
                        f"{100 * trees[pattern]['recall']:.0f}%",
                        *[
                            f"{100 * v.get(pattern, {}).get('recall', 0):.0f}%"
                            for v in gnn_patterns.values()
                        ],
                    ]
                )
            out += [
                "Recall by pattern against T3, on full-volume days, each at its own validation "
                "threshold. This is the direct test of whether a GNN catches what hand-built "
                "graph features miss:",
                "",
            ]
            out += _table(["Pattern", "n", "T3", *list(gnn_patterns)], rows)
            out += [
                "Read recall with precision in mind: an arm can reach high recall by alerting much "
                "more, and its F1 above shows the overall trade-off. On this budget, this table "
                "gives no evidence that GNNs catch patterns the hand-built features miss. A "
                "properly trained GNN could change that.",
                "",
            ]

    # -- validation ----------------------------------------------------------------------------
    out += ["## Detection on validation A", ""]
    rows = []
    base = _load(validation / "baselines.json") or {}
    for arm, result in base.items():
        rows.append(
            [arm, "1", f"{100 * result['minority_f1']['f1']:.2f}", f"{result['pr_auc']:.4f}", "-"]
        )
    for arm, label in ARM_NAMES.items():
        result = _load(validation / f"{arm}.json")
        if result:
            precision = [r["capacity"]["100"]["precision"] for r in result["runs"]]
            rows.append(
                [
                    label,
                    str(len(result["runs"])),
                    _pm(result["f1_mean"], result["f1_std"]),
                    f"{result['pr_auc_mean']:.4f} ± {result['pr_auc_std']:.4f}",
                    f"{100 * sum(precision) / len(precision):.1f}%",
                ]
            )
    for path in sorted(validation.glob("G*_seed*.json")):
        result = _load(path)
        rows.append(
            [
                f"{result['arm']}, {result['protocol']}, CPU budget",
                "1",
                f"{100 * result['val_a_f1']['f1']:.2f}",
                f"{result['val_a_pr_auc']:.4f}",
                "-",
            ]
        )
    out += _table(["Arm", "Seeds", "Minority F1 %", "PR-AUC", "Precision@100"], rows)

    imbalance = _load(validation / "imbalance_study.json")
    if imbalance:
        out += ["## Handling imbalance", "", "T3 seed 0 on validation A, before calibration.", ""]
        out += _table(
            ["Strategy", "PR-AUC", "Log loss", "Mean predicted", "Observed"],
            [
                [
                    k,
                    f"{v['pr_auc']:.4f}",
                    f"{v['log_loss']:.5f}",
                    f"{v['mean_predicted']:.5f}",
                    f"{v['observed_rate']:.5f}",
                ]
                for k, v in imbalance.items()
            ],
        )

    study = _load(validation / "calibration_T3.json")
    if study:
        out += ["## Choosing a calibrator", ""]
        out += [
            f"Fitted on the first half of validation B and compared on the second half. "
            f"Chosen: **{study['chosen']}**, the simplest method within 0.5% of the best log loss.",
            "",
        ]
        rows = [
            [
                "raw",
                f"{study['raw_on_second_half']['log_loss']:.5f}",
                f"{study['raw_on_second_half']['brier_skill']:.4f}",
                f"{study['raw_on_second_half']['adaptive_ece']:.5f}",
                "-",
            ]
        ]
        for method, v in study["methods"].items():
            rows.append(
                [
                    method,
                    f"{v['log_loss']:.5f}",
                    f"{v['brier_skill']:.4f}",
                    f"{v['adaptive_ece']:.5f}",
                    str(v["distinct_values"]),
                ]
            )
        out += _table(
            ["Method", "Log loss", "Brier skill", "Adaptive ECE", "Distinct values"], rows
        )

    shap = _load(validation / "shap_T3.json")
    if shap:
        out += ["## What drives alerts", ""]
        correlations = shap["seed_rank_correlation"]
        if correlations:
            out += [
                f"Rank correlation of feature importance across seeds: "
                f"{min(correlations):.3f} to {max(correlations):.3f}.",
                "",
            ]
        out += _table(
            ["Feature", "Family", "Mean absolute SHAP"],
            [
                [row["description"], row["family"], f"{row['mean_abs_shap']:.3f}"]
                for row in shap["top_features"][:12]
            ],
        )

    # -- streaming -----------------------------------------------------------------------------
    parity = _load(reports / "parity.json")
    stats = _load(paths.features / "stats.json")
    out += ["## Streaming and parity", ""]
    if stats:
        out += [
            f"Feature engine: {stats['events_per_second']:,.0f} events per second on one core of "
            f"a laptop. {100 * stats['truncated_share']:.1f}% of events hit a graph work limit.",
            "",
        ]
    if parity:
        out += [
            f"Full replay through Redpanda, including a `kill -9` of the consumer partway: "
            f"**{'passed' if parity['passed'] else 'FAILED'}**.",
            "",
            f"- Offline rows: {parity['offline_rows']:,}",
            f"- Online messages, including replays after the crash: {parity['online_messages']:,}",
            f"- Vectors identical to offline: {parity['vectors_exact']:,}",
            f"- Within tolerance ({parity['tolerance']}): {parity['vectors_within_tolerance']:,}",
            f"- Missing: {parity['missing']}; unexpected: {parity['extra']}; "
            f"conflicting redeliveries: {parity['conflicting_redeliveries']}",
            "",
        ]

    # -- drift ---------------------------------------------------------------------------------
    drift = _load(validation / "drift_scenarios.json")
    if drift:
        out += ["## Drift injection", ""]
        rows = []
        for name_, scenario in drift["scenarios"].items():
            top = ", ".join(f"{k} ({v})" for k, v in scenario["top"][:3]) or "-"
            label = name_.replace("_", " ").replace("times 1 5", "x 1.5")
            rows.append([label, str(scenario["features_alerting"]), top])
        out += _table(["Scenario", "Features alerting", "Largest PSI"], rows)
        baseline = drift["training_days_replayed_alerts"]
        out += [
            f"Replaying training days raised {sum(baseline)} feature alerts across {len(baseline)} "
            "days. Alert levels are calibrated from those same days, so this confirms the "
            "calibration rather than giving an independent false-alarm rate.",
            "",
        ]

    # -- agent ---------------------------------------------------------------------------------
    agent = _load(test / "agent_rules.json") or _load(validation / "agent_rules_validation.json")
    if agent:
        window = "test" if (test / "agent_rules.json").exists() else "validation"
        out += ["## Investigator: what's measured without an LLM", ""]
        out += [
            f"These run on real alerts from the {window} window, and don't involve a language "
            "model. `scripted-template` is a fixed template, not an AI.",
            "",
        ]
        base_metrics = agent["rule_baseline"]
        scripted = agent["scripted_template"]
        out += [
            f"- Alerts by stratum: {agent['strata_available']}",
            f"- Rule baseline pattern accuracy: {100 * base_metrics['accuracy']:.1f}% "
            f"(macro-F1 {base_metrics['macro_f1']:.3f}, n={base_metrics['n']}). "
            "An LLM has to beat this to justify its cost.",
            f"- Template drafts passing every deterministic check: "
            f"{100 * scripted['citation_validity_rate']:.1f}% of {scripted['drafted']}",
            f"- Template evidence recall: {100 * scripted['evidence_recall']:.1f}%",
            f"- Template declines false positives: "
            f"{100 * scripted['false_positive_decline_rate']:.1f}%; "
            f"misses laundering: {100 * scripted['missed_laundering_rate']:.1f}%",
            "",
            "Verifier detection of seeded errors:",
            "",
        ]
        out += _table(
            ["Mutation", "Applied", "Caught", "Expected to catch"],
            [
                [
                    k.replace("_", " "),
                    str(int(v["applied"])),
                    str(int(v["caught"])),
                    "yes" if v["verifier_expected_to_catch"] else "no: needs a judge or human",
                ]
                for k, v in agent["verifier_mutations"].items()
            ],
        )
    out += [
        "## Not yet measured",
        "",
        "- **LLM narratives:** citation support, pattern accuracy and cost per case need an "
        "`ANTHROPIC_API_KEY`. Run `unravel agent-eval --budget 50`.",
        "- **Judge calibration:** needs human ratings of the sheet that `unravel agent-eval` writes.",
        "- **Published GNN reproduction and full GNN results:** need a GPU. CPU-budget runs "
        "above use short training and small neighbourhoods, and don't reproduce published numbers.",
        "",
    ]
    return "\n".join(out)


def _gnn_lines(paths: DatasetPaths) -> list[str]:
    p1 = _load(paths.reports / "test" / "G2_P1_seed0.json")
    p2 = _load(paths.reports / "test" / "G3_P2_seed0.json")
    if not (p1 and p2):
        return ["- **GNNs:** not yet evaluated."]
    a = 100 * p1["full_volume_days"]["minority_f1"]["f1"]
    b = 100 * p2["full_volume_days"]["minority_f1"]["f1"]
    return [
        f"- **Causal evaluation costs real performance:** the same Multi-PNA on the same budget "
        f"scores F1 {a:.0f} when neighbours may include later edges, as in published protocols, "
        f"and {b:.0f} with strictly earlier edges (one seed each, full-volume days).",
        "- **GNNs:** CPU-budget runs only, on one seed. They trail the trees and don't reproduce "
        "published results, so a GPU run is needed for a fair comparison.",
    ]


def headline(name: str = "HI-Small") -> str:
    """The short results block for the README, computed from the same reports."""
    paths = DatasetPaths(name)
    t3 = _load(paths.reports / "test" / "T3.json")
    t1 = _load(paths.reports / "test" / "T1.json")
    t2 = _load(paths.reports / "test" / "T2.json")
    parity = _load(paths.reports / "parity.json")
    if not (t3 and t1 and t2 and parity):
        return ""
    runs = t3["runs"]
    full = [r["full_volume_days"] for r in runs]
    at_100 = full[0]["capacity"]["100"]
    natural = full[0]["per_pattern"]["natural"]
    named = [v for k, v in full[0]["per_pattern"].items() if k != "natural"]
    named_recall = sum(v["recall"] * v["n"] for v in named) / sum(v["n"] for v in named)
    rows = []
    for label, result in (
        ("Transaction fields only", t1),
        ("+ account history", t2),
        ("+ graph features", t3),
    ):
        r = result["runs"]
        rows.append(
            [
                label,
                _pm(_avg(r, "minority_f1", "f1"), _std(r, "minority_f1", "f1"), digits=1),
                _pm(
                    _avg(r, "full_volume_days", "minority_f1", "f1"),
                    _std(r, "full_volume_days", "minority_f1", "f1"),
                    digits=1,
                ),
            ]
        )
    lines = [
        "## Results",
        "",
        f"On IBM AMLworld HI-Small, using LightGBM with {len(runs)} seeds on a strict temporal "
        "split. Full results are in [docs/results.md](docs/results.md).",
        "",
        *_table(
            ["Features", "Minority F1 %, all test days", "Minority F1 %, full-volume days"], rows
        ),
        "The all-days column uses the same day boundaries as published work, where the best "
        "tree baseline reaches 63.2 and the best GNN 68.2. Those figures aren't directly "
        "comparable: features and sampling differ. The file ends in a laundering-only tail that "
        "inflates any metric including it, so full-volume days are the honest estimate.",
        "",
        f"- **At 100 alerts a day:** {100 * _avg(full, 'capacity', '100', 'precision'):.1f}% precision "
        f"and {100 * _avg(full, 'capacity', '100', 'recall'):.1f}% recall, against a recall ceiling of "
        f"{100 * at_100['recall_ceiling']:.1f}%, on just {int(at_100['days'])} full-volume test days.",
        f"- **The main limitation:** the model recalls {100 * named_recall:.0f}% of laundering in named "
        f'patterns but only {100 * natural["recall"]:.0f}% of "natural" laundering, such as paying '
        f"employees, which makes up {100 * natural['n'] / (natural['n'] + sum(v['n'] for v in named)):.0f}% "
        "of positives on those days.",
        f"- **Parity:** all {parity['offline_rows']:,} feature vectors read back from Redpanda were "
        "identical to offline, across real consumer crashes.",
        *_gnn_lines(paths),
        "- **LLM narratives:** the agent and evaluation are built and tested with a scripted "
        "client. Quality on a real model is not yet measured, as it needs an API key.",
        "",
    ]
    return "\n".join(lines)


def write_results(name: str = "HI-Small") -> Path:
    path = ROOT / "docs" / "results.md"
    path.write_text(build_results(name), encoding="utf-8")
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
    if start in text and end in text:
        before, rest = text.split(start, 1)
        _, after = rest.split(end, 1)
        readme.write_text(f"{before}{start}\n{headline(name)}\n{end}{after}", encoding="utf-8")
    return path
